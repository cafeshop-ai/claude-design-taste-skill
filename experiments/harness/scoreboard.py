#!/usr/bin/env python3
"""Compile every blind comparison into experiments/SCOREBOARD.md.

    python3 scoreboard.py

Reads each iteration-N/<blind-dir>/mapping.json with judgments.json (Claude)
and/or judgments-codex.json (independent judge), and tabulates wins and mean
scores per condition label.
"""
import json
from pathlib import Path

EXP = Path(__file__).resolve().parent.parent
WEB = ["hierarchy", "typography", "color", "content", "craft", "distinctiveness"]


def label(path):
    it, _, cond, _ = Path(path).parts[:4]
    n = it.split("-")[1]
    return f"baseline (it. {n})" if cond == "baseline" else f"skill v{n}"


def main():
    rows = []
    for it in sorted(EXP.glob("iteration-*"), key=lambda p: int(p.name.split("-")[1])):
        for blind in sorted(it.glob("blind*")):
            mapping = json.loads((blind / "mapping.json").read_text())
            for judge, fname in (("Claude", "judgments.json"), ("Codex", "judgments-codex.json")):
                f = blind / fname
                if not f.exists():
                    continue
                js = [j for j in json.loads(f.read_text()) if "error" not in j]
                sides = sorted({label(v) for m in mapping.values() for v in m.values()})
                wins = {s: 0 for s in sides}
                ties = 0
                web = {s: {d: [] for d in WEB} for s in sides}
                for j in js:
                    m = mapping[j["pair"]]
                    if j["preference"] == "tie":
                        ties += 1
                    else:
                        wins[label(m[j["preference"]])] += 1
                    for x in ("X", "Y"):
                        for d in WEB:
                            if d in j["scores"][x]:
                                web[label(m[x])][d].append(j["scores"][x][d])
                a, b = sides
                mean = lambda s, d: f"{sum(web[s][d]) / len(web[s][d]):.1f}" if web[s][d] else "–"
                rows.append((it.name, judge, a, b, wins[a], wins[b], ties,
                             " / ".join(f"{mean(a, d)}→{mean(b, d)}" for d in WEB), len(js)))
    md = ["# Scoreboard",
          "",
          "Every blind pairwise comparison in the experiment. \"Wins\" counts preferred outputs across the 7 cases × 2 runs. "
          "Mean web scores (1–5) are shown as left → right for hierarchy / typography / color / content / craft / "
          "distinctiveness. Generated by `harness/scoreboard.py`; details in each iteration's `judgments*.md`.",
          "",
          "| Iteration | Judge | Left | Right | Wins (left–right, ties) | Web scores, left → right (hier / type / color / content / craft / distinct) |",
          "|---|---|---|---|---|---|"]
    for it, judge, a, b, wa, wb, t, scores, n in rows:
        md.append(f"| {it} | {judge} | {a} | {b} | {wa}–{wb}{f', {t} tie' + ('s' if t != 1 else '') if t else ''} | {scores} |")
    (EXP / "SCOREBOARD.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[5:]))


if __name__ == "__main__":
    main()
